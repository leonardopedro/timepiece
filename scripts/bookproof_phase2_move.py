#!/usr/bin/env python3
"""BOOKPROOF_SPLIT_PLAN.md Phase 2.2: folder `BookProofOperatorCore` along §2.

Each module of the operator core is assigned a §2 area by the name rules of
`scripts/cross_import_matrix.py` (Toolbox, Ns, Qg, Qym, Sm, Qed, Sirk, Ode, Attention,
Textbook, RoadmapAudit) and moved to `BookProof/<Area>/`; the residue that no §2 name
family classifies ("Other") stays at the top level of `BookProof/`, recorded rather than
guessed.  The rewriting is the Phase 1 recipe (`scripts/bookproof_phase1_move.py`).
Phase 2.1 found no clean cut, so no new `[[lean_lib]]` part is introduced (Phase 2.3).

Usage:  python3 scripts/bookproof_phase2_move.py [--dry-run]
"""
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import import_components as ic  # noqa: E402
from bookproof_phase1_move import apply_moves  # noqa: E402
from cross_import_matrix import domain_of  # noqa: E402


def plan_moves():
    moves = {}
    for comp, _roots in ic.components("BookProof"):
        if ic.component_name(comp) != "BookProofOperatorCore":
            continue
        for mod in comp:
            area = domain_of(mod)
            if area == "Other":
                continue
            rest = mod[len("BookProof."):]
            if rest.startswith(area + "."):
                continue  # already in its folder (idempotent re-run)
            moves[mod] = (area, f"BookProof.{area}.{rest}")
    return moves


if __name__ == "__main__":
    moves = plan_moves()
    print(collections.Counter(a for a, _ in moves.values()))
    apply_moves(moves, "BOOKPROOF_PHASE2_MOVES.md",
                "# BookProof Phase 2.2 move map\n\nGenerated by `scripts/bookproof_phase2_move.py` "
                "(BOOKPROOF_SPLIT_PLAN.md Phase 2.2). The operator-core modules not listed here "
                "(the residue no §2 name family classifies) stay at the top level of `BookProof/`. ",
                "--dry-run" in sys.argv)
