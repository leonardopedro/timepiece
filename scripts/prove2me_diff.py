#!/usr/bin/env python3
"""Archive the conversion record of the prove2.me imports and the dependency gaps.

* `converted/diffs/<Name>.diff`: unified diff, original download -> converted module
  (BOOKPROOF_SPLIT_PLAN.md Phase 1.5: "the conversion diff archived next to the download").
* `converted/GAPS.md`: for every download under `converted/blocked/`, the platform
  library modules it imports that are not available, and the inverse index.
"""
import difflib
import json
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DL = os.path.join(ROOT, "Downloads")
CONV = os.path.join(ROOT, "converted")


def group_mod(group):
    return "".join(p[:1].upper() + p[1:] for p in group.split("-"))


def main():
    manifest = json.load(open(os.path.join(DL, "manifest.json")))
    items = [i for i in manifest["items"] if i.get("solution_file")]
    downloaded = {i["theorem_name"].replace(".", "_") for i in items}
    os.makedirs(os.path.join(CONV, "diffs"), exist_ok=True)
    blocked_rows, missing_index = [], defaultdict(list)
    n_ok = 0
    for item in items:
        sf = item["solution_file"]
        name = item["theorem_name"].replace(".", "_")
        g = group_mod(sf.split("/")[0])
        ok = os.path.join(CONV, "Prove2me", g, name + ".lean")
        bl = os.path.join(CONV, "blocked", g, name + ".lean")
        conv = ok if os.path.exists(ok) else bl
        orig_text = open(os.path.join(DL, sf), encoding="utf-8").read().splitlines(True)
        conv_text = open(conv, encoding="utf-8").read().splitlines(True)
        rel = os.path.relpath(conv, ROOT)
        diff = difflib.unified_diff(orig_text, conv_text, fromfile=f"Downloads/{sf}", tofile=rel)
        open(os.path.join(CONV, "diffs", name + ".diff"), "w", encoding="utf-8").writelines(diff)
        if conv == ok:
            n_ok += 1
            continue
        imps = [l.split()[1] for l in orig_text
                if l.startswith("import ") and l.split()[1].startswith(("Definitions.", "Theorems."))]
        missing = [m for m in imps
                   if not (m.startswith("Theorems.Thm_") and m[len("Theorems.Thm_"):] in downloaded)]
        internal = [m for m in imps if m not in missing]
        for m in missing:
            missing_index[m].append(item["theorem_name"])
        blocked_rows.append((sf.split("/")[0], item["theorem_name"], rel, missing, internal))

    out = ["# Dependency gaps of the prove2.me downloads\n\n",
           "Generated by `scripts/prove2me_diff.py`; do not edit by hand.\n\n",
           f"{n_ok} of {len(items)} downloaded solutions are self-contained (Mathlib imports only) "
           "and are converted and compiled under `converted/Prove2me/`. "
           f"The other {len(blocked_rows)} import modules of the prove2.me platform library "
           "(`Definitions.Def_*`, `Theorems.Thm_*`) that are not among the downloads. "
           "Their text is prepared under `converted/blocked/` (provenance header, imports "
           "re-pointed at converted downloads where possible, confirmed lemma renames applied), "
           "but they cannot be compiled or checked until those modules are supplied. "
           "No missing definition has been reconstructed or guessed.\n\n",
           f"Distinct missing platform modules: **{len(missing_index)}** "
           f"({sum(1 for m in missing_index if m.startswith('Definitions.'))} definitions, "
           f"{sum(1 for m in missing_index if m.startswith('Theorems.'))} theorem statements).\n\n",
           "## Per blocked download\n\n",
           "| group | theorem | missing platform modules | imports satisfied by other downloads |\n",
           "|---|---|---|---|\n"]
    for grp, thm, rel, missing, internal in sorted(blocked_rows):
        out.append(f"| `{grp}` | `{thm}` | {', '.join('`'+m+'`' for m in missing)} | "
                   f"{', '.join('`'+m+'`' for m in internal) or '—'} |\n")
    out.append("\n## Missing platform modules (inverse index)\n\n| module | needed by |\n|---|---|\n")
    for m in sorted(missing_index):
        out.append(f"| `{m}` | {', '.join('`'+t+'`' for t in sorted(missing_index[m]))} |\n")
    open(os.path.join(CONV, "GAPS.md"), "w", encoding="utf-8").writelines(out)
    print(f"{n_ok} compiled, {len(blocked_rows)} blocked, {len(missing_index)} missing modules")


if __name__ == "__main__":
    main()
