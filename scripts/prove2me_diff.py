#!/usr/bin/env python3
"""Archive the conversion record of the prove2.me imports and the dependency gaps.

* `converted/diffs/<Name>.diff`: unified diff, original download -> converted module
  (BOOKPROOF_SPLIT_PLAN.md Phase 1.5: "the conversion diff archived next to the download").
* `converted/GAPS.md`: the solutions whose proof uses platform statement stubs
  (`Theorems.Thm_*`), from `converted/stub_dependencies.txt`, and the inverse index.
"""
import difflib
import json
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DL = os.path.join(ROOT, "Downloads")
CONV = os.path.join(ROOT, "converted")


def group_mod(group):
    return "".join(p[:1].upper() + p[1:] for p in group.split("-"))


def main():
    manifest = json.load(open(os.path.join(DL, "manifest.json")))
    items = [i for i in manifest["items"] if i.get("solution_file")]
    downloaded = {i["theorem_name"].replace(".", "_") for i in items}
    os.makedirs(os.path.join(CONV, "diffs"), exist_ok=True)
    blocked_rows, missing_index = [], defaultdict(list)
    n_ok = 0
    for item in items:
        sf = item["solution_file"]
        name = item["theorem_name"].replace(".", "_")
        g = group_mod(sf.split("/")[0])
        ok = os.path.join(CONV, "Prove2me", g, name + ".lean")
        bl = os.path.join(CONV, "blocked", g, name + ".lean")
        conv = ok if os.path.exists(ok) else bl
        orig_text = open(os.path.join(DL, sf), encoding="utf-8").read().splitlines(True)
        conv_text = open(conv, encoding="utf-8").read().splitlines(True)
        rel = os.path.relpath(conv, ROOT)
        diff = difflib.unified_diff(orig_text, conv_text, fromfile=f"Downloads/{sf}", tofile=rel)
        open(os.path.join(CONV, "diffs", name + ".diff"), "w", encoding="utf-8").writelines(diff)
        if conv == ok:
            n_ok += 1
            continue
        imps = [l.split()[1] for l in orig_text
                if l.startswith("import ") and l.split()[1].startswith(("Definitions.", "Theorems."))]
        missing = [m for m in imps
                   if not (m.startswith("Theorems.Thm_") and m[len("Theorems.Thm_"):] in downloaded)]
        internal = [m for m in imps if m not in missing]
        for m in missing:
            missing_index[m].append(item["theorem_name"])
        blocked_rows.append((sf.split("/")[0], item["theorem_name"], rel, missing, internal))

    # GAPS.md: every solution compiles; the remaining gaps are the platform statement stubs
    # (`Theorems.Thm_*`, `:= by sorry` by platform design) in a solution's dependency cone,
    # as listed by `scripts/prove2me_stub_cone.lean` in `converted/stub_dependencies.txt`.
    cone = {}
    sd = os.path.join(CONV, "stub_dependencies.txt")
    if os.path.exists(sd):
        for line in open(sd, encoding="utf-8"):
            if " :: " not in line:
                continue
            sol, rest = line.rstrip("\n").split(" :: ", 1)
            cone[sol] = [tuple(x.split(" @ ")) for x in rest.split(" ; ")]
    sol_info = {"Prove2me.Solution." + i["theorem_name"].replace(".", "_"):
                (i["solution_file"].split("/")[0], i["theorem_name"]) for i in items}
    inverse = defaultdict(set)
    for sol, ds in cone.items():
        for d, m in ds:
            inverse[(d, m)].add(sol_info.get(sol, ("?", sol))[1])
    out = ["# Remaining gaps of the converted prove2.me downloads\n\n",
           "Generated by `scripts/prove2me_diff.py` from `converted/stub_dependencies.txt` "
           "(itself produced by `scripts/prove2me_stub_cone.lean`); do not edit by hand.\n\n",
           f"All {len(items)} downloaded solutions are converted and compile under "
           f"`converted/Prove2me/` ({n_ok} found). "
           "The platform library they import (`Definitions.Def_*`, `Theorems.Thm_*`, supplied as "
           "`Downloads/_deps/`) is converted under `converted/Definitions/` and "
           "`converted/Theorems/`. No platform module is missing.\n\n",
           f"**{len(items) - len(cone)}** solutions are fully proved: their axioms are among "
           "`propext`, `Classical.choice`, `Quot.sound`. "
           f"**{len(cone)}** solutions use, as hypotheses, platform theorems that are only "
           "*statement stubs* in the download: a `Theorems.Thm_X` module of the platform states "
           "`X` and ends in `:= by sorry` by platform design, and the accepted proof of `X` is a "
           "separate submission that is not among the downloads (see `Downloads/_deps/README.md`). "
           "On the platform these solutions are checked against the same stubs, so the converted "
           "solutions are exactly as proved as the originals: proofs of the main statement "
           "relative to the stub statements listed below. "
           f"Distinct stub theorems used: **{len(inverse)}**.\n\n",
           "## Solutions whose proof uses platform statement stubs\n\n",
           "| group | theorem | stub theorems used (module) |\n|---|---|---|\n"]
    for sol in sorted(cone, key=lambda s: sol_info.get(s, ("?", s))):
        grp, thm = sol_info.get(sol, ("?", sol))
        out.append(f"| `{grp}` | `{thm}` | " +
                   ", ".join(f"`{d}` (`{m}`)" for d, m in cone[sol]) + " |\n")
    out.append("\n## Stub theorems (inverse index)\n\n| stub theorem | module | used by |\n|---|---|---|\n")
    for (d, m) in sorted(inverse):
        out.append(f"| `{d}` | `{m}` | " + ", ".join(f"`{t}`" for t in sorted(inverse[(d, m)])) + " |\n")
    open(os.path.join(CONV, "GAPS.md"), "w", encoding="utf-8").writelines(out)
    print(f"{n_ok} converted, {len(cone)} relative to stubs, {len(inverse)} stub theorems")

if __name__ == "__main__":
    main()
