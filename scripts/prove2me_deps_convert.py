#!/usr/bin/env python3
"""Convert the prove2.me platform library (`Downloads/_deps/`) to Lean 4.28.0.

`Downloads/_deps/` holds the verbatim platform modules that the downloaded
solutions import: `Definitions/Def_*.lean` (definition code) and
`Theorems/Thm_*.lean` (statement stubs, ending `:= by sorry` by platform design).

This script writes them as modules of the lake library `Prove2mePlatform`
(`srcDir = "converted"`), keeping their platform module names so that the
solution sources' `import Definitions.Def_X` / `import Theorems.Thm_X` lines
resolve unchanged:

* `converted/Definitions/Def_X.lean` -- the platform text with the confirmed
  lemma renames of `prove2me_convert.RENAMES` applied;
* `converted/Theorems/Thm_X.lean`    -- for a theorem whose accepted solution is
  among the downloads, a one-line re-export of the converted (proved) solution
  module `Prove2me.<Group>.X`, so that the statement is declared exactly once and
  carries a proof; for every other theorem, the platform statement stub
  (still ending in `sorry`).

Existing files are left alone unless `--force` is given, so hand conversion
edits are never overwritten.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from prove2me_convert import DL, ROOT, apply_renames, module_of, name_mod  # noqa: E402

DEPS = os.path.join(DL, "_deps")
OUT = os.path.join(ROOT, "converted")

HEAD = """/-
prove2.me platform library module `{mod}`, converted to Lean 4.28.0.
Original text: `Downloads/_deps/{rel}` (platform Mathlib rev {rev}).
Public prove2.me contributions are licensed under Apache 2.0 (https://prove2.me/terms).
-/
"""


def main(force: bool) -> None:
    manifest = json.load(open(os.path.join(DL, "manifest.json")))
    items = [i for i in manifest["items"] if i.get("solution_file")]
    by_key = {name_mod(i["theorem_name"]): i for i in items}
    dm = json.load(open(os.path.join(DEPS, "manifest.json")))
    rev = {it["module"]: it.get("mathlib_rev", "?")[:12] for it in dm["items"]}
    written = 0
    for sub in ("Definitions", "Theorems"):
        os.makedirs(os.path.join(OUT, sub), exist_ok=True)
        for fn in sorted(os.listdir(os.path.join(DEPS, sub))):
            if not fn.endswith(".lean"):
                continue
            dst = os.path.join(OUT, sub, fn)
            if os.path.exists(dst) and not force:
                continue
            mod = f"{sub}.{fn[:-5]}"
            rel = f"{sub}/{fn}"
            text = open(os.path.join(DEPS, sub, fn), encoding="utf-8").read()
            key = fn[len("Thm_"):-5]
            if sub == "Theorems" and key in by_key:
                dep = by_key[key]
                out = (HEAD.format(mod=mod, rel=rel, rev=rev.get(mod, "?"))
                       + f"\nimport {module_of(dep)}\n\n"
                       f"/-! The platform statement stub `{rel}` is replaced by the converted\n"
                       f"accepted solution `{module_of(dep)}`, which declares the same\n"
                       f"theorem `{dep['theorem_name']}` together with its proof. -/\n")
            else:
                out = HEAD.format(mod=mod, rel=rel, rev=rev.get(mod, "?")) + apply_renames(text).rstrip() + "\n"
            open(dst, "w", encoding="utf-8").write(out)
            written += 1
    print(f"wrote {written} modules")
    write_aggregators()


# Platform modules that are not part of the build: the 299-module `Def_OAIE3v2B*` chain
# (about 550k lines of proof bundles) is imported by no downloaded solution and by no other
# platform module, so it is kept as converted text only (see `converted/README.md`).
UNBUILT_PREFIXES = ("Def_OAIE3v2B",)


def write_aggregators() -> None:
    for sub, what in (("Definitions", "definition modules"), ("Theorems", "theorem modules")):
        mods = sorted(fn[:-5] for fn in os.listdir(os.path.join(OUT, sub))
                      if fn.endswith(".lean") and not fn.startswith(UNBUILT_PREFIXES))
        text = (f"/-\nAggregator of the converted prove2.me platform {what} (`{sub}.*`),\n"
                f"generated by `scripts/prove2me_deps_convert.py`.\n-/\n"
                + "".join(f"import {sub}.{m}\n" for m in mods))
        open(os.path.join(OUT, sub + ".lean"), "w", encoding="utf-8").write(text)


if __name__ == "__main__":
    main("--force" in sys.argv)
