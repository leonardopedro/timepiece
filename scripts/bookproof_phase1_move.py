#!/usr/bin/env python3
"""BOOKPROOF_SPLIT_PLAN.md Phase 1: folder the independent parts of `BookProof/`.

Every multi-module independent part except `BookProofOperatorCore` and
`BookProofAttention` moves into `BookProof/<Part>/` (part name without the
`BookProof` prefix): `BookProof/<X>.lean` -> `BookProof/<Part>/<X>.lean`, i.e. the
module `BookProof.<X>` becomes `BookProof.<Part>.<X>`.

What is rewritten (in the same commit):
* `import BookProof.<X>` lines in every first-party `.lean` file (module names only;
  declaration names such as `BookProof.<X>.foo` live in namespaces and are unchanged,
  because moving a file does not change the namespaces it declares);
* the anchors of `COMPONENT_NAMES` in `scripts/import_components.py`;
* file paths `BookProof/<X>.lean` in the repository's Markdown documentation, except
  the append-only `CONSOLIDATED_PLAN.md` (historical entries keep their paths; the
  move map is recorded in `BOOKPROOF_PHASE1_MOVES.md`).

The lake stanzas are regenerated afterwards with
`python3 scripts/import_components.py BookProof --write-lakefile`.

Usage:  python3 scripts/bookproof_phase1_move.py [--dry-run]
"""
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import import_components as ic  # noqa: E402

EXCLUDED_PARTS = {"BookProofOperatorCore", "BookProofAttention"}
SKIP_DIRS = {".lake", ".git", "Downloads", "converted"}


def plan_moves():
    moves = {}
    for comp, _roots in ic.components("BookProof"):
        name = ic.component_name(comp)
        if len(comp) < 2 or name is None or name in EXCLUDED_PARTS:
            continue
        folder = name[len("BookProof"):]
        for mod in comp:
            rest = mod[len("BookProof."):]
            if rest.startswith(folder + "."):
                continue  # already in its folder (idempotent re-run)
            moves[mod] = (folder, f"BookProof.{folder}.{rest}")
    return moves


def files_with(ext):
    for root, dirs, files in os.walk("."):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            if f.endswith(ext):
                yield os.path.join(root, f)


def apply_moves(moves, map_file, title, dry=False):
    print(f"{len(moves)} modules in {len({f for f, _ in moves.values()})} parts")
    if dry:
        return
    for old, (folder, new) in sorted(moves.items()):
        src = old.replace(".", "/") + ".lean"
        dst = new.replace(".", "/") + ".lean"
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        subprocess.run(["git", "mv", src, dst], check=True)
    imp_re = re.compile(r"^(\s*import\s+)(BookProof\.[A-Za-z0-9_.]+)(\s|$)", re.M)

    def fix_imports(m):
        mod = m.group(2)
        return m.group(1) + (moves[mod][1] if mod in moves else mod) + m.group(3)

    n_lean = 0
    for path in files_with(".lean"):
        text = open(path, encoding="utf-8", errors="surrogateescape").read()
        new = imp_re.sub(fix_imports, text)
        if new != text:
            open(path, "w", encoding="utf-8", errors="surrogateescape").write(new)
            n_lean += 1
    # COMPONENT_NAMES anchors
    p = "scripts/import_components.py"
    text = open(p, encoding="utf-8").read()
    for old, (_f, new) in moves.items():
        text = text.replace(f'"{old}"', f'"{new}"')  # COMPONENT_NAMES, SUB_SYSTEM_TARGETS
    open(p, "w", encoding="utf-8").write(text)
    # Markdown paths
    path_map = {old.replace(".", "/") + ".lean": new.replace(".", "/") + ".lean"
                for old, (_f, new) in moves.items()}
    path_re = re.compile(r"BookProof/[A-Za-z0-9_/]+\.lean")
    n_md = 0
    for path in (p for ext in (".md", ".lean", ".py", ".sh", ".rs", ".toml", ".txt", ".tex")
                 for p in files_with(ext)):
        if os.path.basename(path) == "CONSOLIDATED_PLAN.md" or path.endswith("_MOVES.md"):
            continue
        text = open(path, encoding="utf-8", errors="surrogateescape").read()
        new = path_re.sub(lambda m: path_map.get(m.group(0), m.group(0)), text)
        if new != text:
            open(path, "w", encoding="utf-8", errors="surrogateescape").write(new)
            n_md += 1
    with open(map_file, "w", encoding="utf-8") as fh:
        fh.write(title + "Module names changed; declaration names did not.\n\n"
                 "| part folder | old module | new module |\n|---|---|---|\n")
        for old, (folder, new) in sorted(moves.items(), key=lambda kv: (kv[1][0], kv[0])):
            fh.write(f"| `{folder}/` | `{old}` | `{new}` |\n")
    print(f"rewrote imports in {n_lean} .lean files, paths in {n_md} .md files")


if __name__ == "__main__":
    apply_moves(plan_moves(), "BOOKPROOF_PHASE1_MOVES.md",
                "# BookProof Phase 1 move map\n\nGenerated by `scripts/bookproof_phase1_move.py` "
                "(BOOKPROOF_SPLIT_PLAN.md Phase 1). ", "--dry-run" in sys.argv)
